/**
 * Fast lookup helper by slug
 */
export const getKeywordBySlug = (slug) => {
  if (!slug) return null;
  const clean = String(slug).toLowerCase().trim();
  return TRENDING_KEYWORDS_DATA.find((k) => k.slug === clean || k.slug.replace(/-jobs$/, '') === clean) || null;
};
