class CompanyPortalsProvider extends JobProvider {
  constructor() {
    super('company_portals', { enabled: true });
  }

  isEnabled() {
    return true;
  }

  async fetch() {
    const allJobs = [];

    for (const group of DIRECT_COMPANY_FEEDS) {
      for (const item of group.jobs) {
        const { category, subCategory } = classifyJob(item.title, item.description);
        const extractedSkills = extractSkills(item.title, item.description, item.skills, category);

        allJobs.push({
          jobId: `portal_${group.company.toLowerCase().replace(/[^a-z0-9]/g, '')}_${item.title.toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 40)}`,
          title: item.title,
          headline: `${item.title} at ${group.company}`,
          company: group.company,
          logo: group.logo,
          companyWebsite: `https://${group.domain}`,
          description: item.description,
          location: item.location,
          country: 'India',
          state: item.location.includes(',') ? item.location.split(',')[1].trim() : '',
          city: item.location.includes(',') ? item.location.split(',')[0].trim() : item.location,
          workMode: item.workMode || 'hybrid',
          employmentType: item.employmentType || 'full-time',
          experienceLevel: item.experienceLevel || 'mid',
          category,
          subCategory,
          requiredSkills: extractedSkills,
          salary: item.salaryMin,
          salaryMin: item.salaryMin,
          salaryMax: item.salaryMax,
          currency: item.currency || 'INR',
          link: item.url,
          source: 'company_portals',
          postedDate: new Date(),
        });
      }
    }

    return allJobs;
  }
}

module.exports = CompanyPortalsProvider;
